#!/usr/bin/env python3
"""Wrap the guide pages (page bodies, as published to claude.ai) in full HTML
documents so they open directly in a browser and work on GitHub Pages.

Run: python3 tools/build_docs.py
  docs/etube-tap-guide.html  ->  docs/index.html
  docs/media-guide.html      ->  docs/media.html
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = [
    ("etube-tap-guide.html", "index.html"),
    ("media-guide.html", "media.html"),
]

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- Generated by tools/build_docs.py from {src}. Edit that file instead. -->
<style>:root{{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}body{{margin:0}}img{{max-width:100%}}[hidden]{{display:none!important}}</style>
"""


def main():
    for src_name, out_name in PAGES:
        src = ROOT / "docs" / src_name
        out = ROOT / "docs" / out_name
        body = src.read_text(encoding="utf-8")
        # <title>, <meta>, <link> and <style> from the page belong in <head>
        split = body.index('<div class="shell">')
        out.write_text(HEAD.format(src=src_name) + body[:split] + "</head>\n<body>\n"
                       + body[split:] + "\n</body>\n</html>\n", encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
